#!/usr/bin/env python3
"""Tree digest of any pack directory, recorded in its sidecar ``packs/<name>.source.yaml``.

The algorithm is spec-kitty core's ``snapshot_sha256`` (charter.offering.packs.pack_manifest),
reimplemented here so no core install is needed: SHA-256 over every regular file of a pack
directory except the top-level ``pack-manifest.yaml``, in order of POSIX relative path, each
contributing an 8-byte big-endian path length, the UTF-8 path, an 8-byte big-endian size and the
raw bytes. A symlink or a special file refuses. Only git-tracked files count (``git ls-files``),
read from disk, so untracked and ignored files cannot change the digest; outside a git work tree
the script refuses.

Every directory under ``packs/`` that holds a ``pack.yaml`` is a pack and has a sidecar.

    python3 scripts/ci/pack_digest.py [PACK ...]          # print "<digest>  packs/<name>" per pack
    python3 scripts/ci/pack_digest.py --check [PACK ...]  # verify; with no PACK also report orphan sidecars
    python3 scripts/ci/pack_digest.py --update [PACK ...] # restamp stale, create missing; refuse malformed

PACK is a directory name under packs/. Exit: 0 all fresh or update done; 1 any violation (check)
or refusal (update); 2 usage error (unknown PACK).
"""

from __future__ import annotations

import argparse
import hashlib
import os
import re
import subprocess
import sys
from dataclasses import dataclass
from collections.abc import Callable
from pathlib import Path

import yaml

REPO_ROOT = Path(__file__).resolve().parents[2]
PACKS = REPO_ROOT / "packs"
MANIFEST = "pack-manifest.yaml"
ALGORITHM = "spec-kitty-snapshot-sha256"
SIDECAR_SUFFIX = ".source.yaml"

_HEX64 = re.compile(r"[0-9a-f]{64}")
_VALUE_LINE = re.compile(r"^(\s+value:\s*)([0-9a-f]{64})\s*$")

_TEMPLATE = """\
# Recorded tree digest of packs/{name}/ (spec-kitty-open-packs#194).
# Generated by `python3 scripts/ci/pack_digest.py --update`; scripts/ci/check-pack-digests.sh
# verifies it. The algorithm is spec-kitty-snapshot-sha256 (see scripts/ci/pack_digest.py).
tree_digest:
  algorithm: {algorithm}
  value: {value}
"""


class SidecarError(ValueError):
    """A sidecar that cannot be read as a recorded digest."""


@dataclass(frozen=True)
class PackStatus:
    name: str
    state: str  # fresh | stale | missing | malformed | refused
    actual: str
    recorded: str = ""
    message: str = ""


def tracked_files(root: Path) -> list[str]:
    """POSIX paths, relative to ``root``, of the git-tracked files under it.

    Untracked and ignored files (``__pycache__``, editor droppings) never count, so a local run
    and CI see the same tree. A tracked file that is modified or staged but not committed is
    listed too and hashed from disk, which is what ``--update`` needs before the commit.
    A tracked file deleted on disk is skipped, as it will be once the deletion is committed.
    A brand-new file counts once it is ``git add``-ed.
    """
    try:
        out = subprocess.run(
            ["git", "-C", str(root), "ls-files", "-z", "--", "."], check=True, capture_output=True
        ).stdout
    except (OSError, subprocess.CalledProcessError) as exc:
        raise OSError(f"{root} is not inside a git work tree; the digest covers tracked files only") from exc
    return [entry.decode("utf-8") for entry in out.split(b"\0") if entry]


def snapshot_sha256(root: Path, lister: Callable[[Path], list[str]] = tracked_files) -> str:
    digest = hashlib.sha256()
    for posix in sorted(lister(root)):
        path = root / posix
        if path.is_symlink():
            raise OSError(f"Snapshot contains unsupported symlink: {posix}")
        if posix == MANIFEST or not os.path.lexists(path):  # a tracked file deleted on disk is gone
            continue
        if not path.is_file():
            raise OSError(f"Snapshot contains unsupported file type: {posix}")
        name = posix.encode("utf-8")
        digest.update(len(name).to_bytes(8, "big") + name)
        digest.update(path.stat().st_size.to_bytes(8, "big") + path.read_bytes())
    return digest.hexdigest()


def discover_packs(packs_root: Path) -> list[Path]:
    return sorted(d for d in packs_root.iterdir() if d.is_dir() and (d / "pack.yaml").is_file())


def sidecar_path(pack_dir: Path) -> Path:
    return pack_dir.parent / f"{pack_dir.name}{SIDECAR_SUFFIX}"


def orphan_sidecars(packs_root: Path) -> list[Path]:
    packs = {d.name for d in discover_packs(packs_root)}
    return sorted(
        p for p in packs_root.glob(f"*{SIDECAR_SUFFIX}")
        if p.is_file() and p.name[: -len(SIDECAR_SUFFIX)] not in packs
    )


def _digest_mapping(sidecar: Path) -> dict:
    try:
        data = yaml.safe_load(sidecar.read_text(encoding="utf-8"))
    except (yaml.YAMLError, UnicodeDecodeError) as exc:
        raise SidecarError(f"{sidecar.name} is not readable YAML: {type(exc).__name__}") from exc
    block = data.get("tree_digest") if isinstance(data, dict) else None
    if not isinstance(block, dict):
        raise SidecarError(f"{sidecar.name} has no tree_digest mapping")
    return block


def recorded_digest(sidecar: Path) -> str:
    block = _digest_mapping(sidecar)
    if block.get("algorithm") != ALGORITHM:
        raise SidecarError(f"{sidecar.name} tree_digest.algorithm is not {ALGORITHM}")
    value = block.get("value")
    if not isinstance(value, str) or not _HEX64.fullmatch(value):
        raise SidecarError(f"{sidecar.name} tree_digest.value is not 64 lowercase hex characters")
    return value


def pack_status(pack_dir: Path) -> PackStatus:
    try:
        actual = snapshot_sha256(pack_dir)
    except OSError as exc:  # symlink or special file inside the pack: the recipe refuses it
        return PackStatus(pack_dir.name, "refused", "", message=f"packs/{pack_dir.name}/ cannot be hashed: {exc}")
    sidecar = sidecar_path(pack_dir)
    if not sidecar.is_file():
        return PackStatus(pack_dir.name, "missing", actual)
    try:
        recorded = recorded_digest(sidecar)
    except SidecarError as exc:
        return PackStatus(pack_dir.name, "malformed", actual, message=str(exc))
    return PackStatus(pack_dir.name, "fresh" if recorded == actual else "stale", actual, recorded)


def _rel(path: Path, packs_root: Path) -> str:
    return path.relative_to(packs_root.parent).as_posix()


def _fail(sidecar_rel: str, reason: str, remedy: str) -> None:
    print(f"::error file={sidecar_rel}::{reason}; {remedy}")


def _remedy(name: str) -> str:
    return f"run `python3 scripts/ci/pack_digest.py --update {name}`"


def _report_failure(status: PackStatus, sidecar_rel: str) -> None:
    name = status.name
    if status.state == "stale":
        _fail(sidecar_rel, f"packs/{name}/ digest {status.actual} != recorded {status.recorded}", _remedy(name))
    elif status.state == "missing":
        _fail(sidecar_rel, f"packs/{name}/ has no recorded digest", _remedy(name))
    elif status.state == "refused":
        _fail(f"packs/{name}", status.message, "remove the symlink or special file from the pack")
    else:
        _fail(sidecar_rel, status.message, "fix the sidecar by hand; --update refuses a malformed one")


def _select(packs_root: Path, names: list[str] | None) -> list[Path] | None:
    packs = discover_packs(packs_root)
    if not names:
        return packs
    by_name = {d.name: d for d in packs}
    unknown = [n for n in names if n not in by_name]
    if unknown:
        print(f"error: unknown pack: {', '.join(unknown)}", file=sys.stderr)
        return None
    return [by_name[n] for n in names]


def _no_pack() -> int:
    print("::error::no pack found under packs/")
    return 1


def check(packs_root: Path, names: list[str] | None = None) -> int:
    selected = _select(packs_root, names)
    if selected is None:
        return 2
    if not discover_packs(packs_root):
        return _no_pack()
    failures = 0
    for pack_dir in selected:
        status = pack_status(pack_dir)
        if status.state == "fresh":
            print(f"ok: packs/{status.name}/ digest matches {status.recorded}")
            continue
        failures += 1
        _report_failure(status, _rel(sidecar_path(pack_dir), packs_root))
    if not names:
        for orphan in orphan_sidecars(packs_root):
            failures += 1
            stem = orphan.name[: -len(SIDECAR_SUFFIX)]
            _fail(_rel(orphan, packs_root), f"no pack directory packs/{stem}/ for this sidecar", "delete it")
    return 1 if failures else 0


def _write(path: Path, text: str) -> None:
    with path.open("w", encoding="utf-8", newline="") as handle:
        handle.write(text)


def _restamp(text: str, value: str) -> str | None:
    """Replace the digest value under ``tree_digest:``; None unless exactly one line matches."""
    newline = "\r\n" if "\r\n" in text else "\n"
    lines = text.split(newline)
    starts = [i for i, line in enumerate(lines) if re.match(r"^tree_digest:\s*$", line)]
    if len(starts) != 1:
        return None
    hits = []
    for i in range(starts[0] + 1, len(lines)):
        line = lines[i]
        if line.strip() and not line[0].isspace():
            break
        if _VALUE_LINE.match(line):
            hits.append(i)
    if len(hits) != 1:
        return None
    lines[hits[0]] = _VALUE_LINE.sub(lambda m: m.group(1) + value, lines[hits[0]])
    return newline.join(lines)


def _update_stale(status: PackStatus, sidecar: Path, sidecar_rel: str) -> bool:
    with sidecar.open(encoding="utf-8", newline="") as handle:  # keep CRLF as found
        new = _restamp(handle.read(), status.actual)
    if new is None:
        _fail(sidecar_rel, "tree_digest.value is not a plain 64-hex line", "fix the sidecar by hand; --update refuses it")
        return False
    _write(sidecar, new)
    print(f"updated: {sidecar_rel}")
    return True


def update(packs_root: Path, names: list[str] | None = None) -> int:
    selected = _select(packs_root, names)
    if selected is None:
        return 2
    if not discover_packs(packs_root):
        return _no_pack()
    refused = 0
    for pack_dir in selected:
        status = pack_status(pack_dir)
        sidecar = sidecar_path(pack_dir)
        rel = _rel(sidecar, packs_root)
        if status.state == "missing":
            _write(sidecar, _TEMPLATE.format(name=status.name, algorithm=ALGORITHM, value=status.actual))
            print(f"created: {rel}")
        elif status.state == "stale":
            refused += not _update_stale(status, sidecar, rel)
        elif status.state in ("malformed", "refused"):
            refused += 1
            _report_failure(status, rel)
    if not names:
        for orphan in orphan_sidecars(packs_root):
            print(f"::warning file={_rel(orphan, packs_root)}::no pack directory for this sidecar; delete it")
    return 1 if refused else 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--check", action="store_true", help="verify the recorded digests (fail closed)")
    mode.add_argument("--update", action="store_true", help="restamp stale sidecars, create missing ones")
    parser.add_argument("packs", nargs="*", metavar="PACK", help="pack directory names (default: every pack)")
    args = parser.parse_args(argv)
    if args.check:
        return check(PACKS, args.packs)
    if args.update:
        return update(PACKS, args.packs)
    selected = _select(PACKS, args.packs)
    if selected is None:
        return 2
    code = 0
    for pack_dir in selected:
        status = pack_status(pack_dir)
        if status.state == "refused":
            _report_failure(status, "")
            code = 1
        else:
            print(f"{status.actual}  packs/{pack_dir.name}")
    return code


if __name__ == "__main__":
    sys.exit(main())
